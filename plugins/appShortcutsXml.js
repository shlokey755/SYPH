/**
 * appShortcutsXml.js
 * Pure helpers for plugins/withAppShortcuts.js: check the shortcut list from app.json and write the two Android XML files
 * (res/xml/shortcuts.xml and the labels in res/values). No Expo or file-system code here, so a unit test can run it.
 */

const ID_PATTERN = /^[a-z][a-z0-9_]*$/;

const escapeXml = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Android string resources need a backslash before an apostrophe, and "@" or "?" at the start would be read as a reference. */
const escapeAndroidString = (text) => escapeXml(String(text).replace(/'/g, "\\'").replace(/^([@?])/, '\\$1'));

/**
 * Checks and tidies the list. Throws with a plain message when an entry is wrong, so a typo stops the build instead of
 * producing a menu that silently lacks an entry. Android shows about four entries, and recommends a short label of at most
 * 10 characters and a long one of at most 25 (longer ones are cut off).
 */
function normalizeShortcuts(raw) {
  if (!Array.isArray(raw) || raw.length === 0) throw new Error('withAppShortcuts: "shortcuts" must be a non-empty list');
  if (raw.length > 4) throw new Error('withAppShortcuts: Android launchers show at most 4 shortcuts');
  const seen = new Set();
  return raw.map((entry, index) => {
    const where = `withAppShortcuts: shortcut ${index + 1}`;
    const { id, shortLabel, longLabel, icon, url } = entry ?? {};
    if (typeof id !== 'string' || !ID_PATTERN.test(id)) throw new Error(`${where}: "id" must be lower-case letters, digits and _`);
    if (seen.has(id)) throw new Error(`${where}: id "${id}" is used twice`);
    seen.add(id);
    if (typeof shortLabel !== 'string' || !shortLabel.trim()) throw new Error(`${where} (${id}): "shortLabel" is missing`);
    if (shortLabel.length > 10) throw new Error(`${where} (${id}): "shortLabel" is longer than 10 characters`);
    if (longLabel !== undefined && (typeof longLabel !== 'string' || !longLabel.trim() || longLabel.length > 25)) {
      throw new Error(`${where} (${id}): "longLabel" must be 1 to 25 characters`);
    }
    if (typeof icon !== 'string' || !ID_PATTERN.test(icon)) throw new Error(`${where} (${id}): "icon" must be the name of a file in assets/shortcuts`);
    if (typeof url !== 'string' || !/^[a-z][a-z0-9+.-]*:\/\/\S+$/i.test(url)) throw new Error(`${where} (${id}): "url" must be a link such as syph://shortcut/me`);
    return { id, shortLabel: shortLabel.trim(), longLabel: (longLabel ?? shortLabel).trim(), icon, url };
  });
}

const shortKey = (id) => `syph_shortcut_${id}_short`;
const longKey = (id) => `syph_shortcut_${id}_long`;

/** res/xml/shortcuts.xml: one entry per shortcut, each opening its link in SYPH's own main screen. */
function buildShortcutsXml(shortcuts, packageName) {
  const entries = shortcuts
    .map(
      (s) => `  <shortcut
      android:shortcutId="${s.id}"
      android:enabled="true"
      android:icon="@drawable/${s.icon}"
      android:shortcutShortLabel="@string/${shortKey(s.id)}"
      android:shortcutLongLabel="@string/${longKey(s.id)}">
    <intent
        android:action="android.intent.action.VIEW"
        android:data="${escapeXml(s.url)}"
        android:targetPackage="${packageName}"
        android:targetClass="${packageName}.MainActivity" />
  </shortcut>`
    )
    .join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAppShortcuts.js from app.json. Do not edit: change the plugin's "shortcuts" list in app.json. -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
${entries}
</shortcuts>
`;
}

/** res/values/syph_shortcuts.xml: the labels. A shortcut's labels must be string resources. */
function buildStringsXml(shortcuts) {
  const strings = shortcuts
    .flatMap((s) => [
      `  <string name="${shortKey(s.id)}">${escapeAndroidString(s.shortLabel)}</string>`,
      `  <string name="${longKey(s.id)}">${escapeAndroidString(s.longLabel)}</string>`,
    ])
    .join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAppShortcuts.js from app.json. Do not edit. -->
<resources>
${strings}
</resources>
`;
}

module.exports = { normalizeShortcuts, buildShortcutsXml, buildStringsXml, escapeAndroidString };
